package com.example.bloodpressurerecord.domain.model

/**
 * 血压分级，采用《中国高血压防治指南》成人诊室血压标准。
 *
 * LOW 为本应用附加的“偏低”提示（收缩压 <90 或舒张压 <60），
 * 不属于指南分级，仅用于提醒关注。
 */
enum class BloodPressureCategory {
    /** 偏低提示：收缩压 <90 或舒张压 <60。 */
    LOW,

    /** 正常：收缩压 <120 且舒张压 <80。 */
    NORMAL,

    /** 正常高值：收缩压 120–139 和/或舒张压 80–89。 */
    HIGH_NORMAL,

    /** 1级高血压：收缩压 140–159 和/或舒张压 90–99。 */
    STAGE1,

    /** 2级高血压：收缩压 160–179 和/或舒张压 100–109。 */
    STAGE2,

    /** 3级高血压：收缩压 ≥180 和/或舒张压 ≥110。 */
    STAGE3
}
